"""Regression tests for research-prompt intent normalization.

Run from backend/:
    python utils/test_intent_research_prompts.py

These tests deliberately exercise the deterministic fallback path because the
bug being fixed occurs when Groq intent resolution is unavailable/exhausted.
"""
from __future__ import annotations

import asyncio
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import utils.intent as intent_mod


PROMPTS = [
    """Generate a comprehensive research report assessing whether India’s private-bank credit cycle can sustain strong loan growth and profitability through 2030 without creating a material deterioration in asset quality. Examine credit growth across retail, corporate, MSME, housing, and unsecured segments, deposit growth, credit-to-deposit ratios, funding costs, net interest margins, provisioning, capital adequacy, liquidity, asset quality, borrower leverage, and competitive intensity. Compare the current cycle with India’s 2008–09, 2014–18, and 2020–22 credit cycles and identify the structural differences. Evaluate how changes in deposit costs, credit growth, provisioning, and competition could affect ROA and ROE. Compare RBI commentary, bank management commentary, rating agencies, institutional investors, and analysts. Identify the assumptions and scenarios that would strengthen or weaken the banking-cycle outlook. Produce a fully structured research report with evidence-backed charts, tables, historical comparisons, sensitivity analysis, and claim-level citations.""",
    """Generate a comprehensive research report assessing whether India’s FMCG industry can sustain revenue growth, volume growth, and margin expansion through 2030. Examine urban versus rural consumption, household income growth, pricing, premiumization, commodity inflation, gross margins, advertising and promotion spending, distribution costs, modern trade, quick commerce, private labels, inventory, and competitive intensity. Distinguish between growth generated by pricing, mix, and true consumption volumes. Evaluate whether premiumization can offset slowing underlying volume growth and how a reversal in commodity prices would affect margins. Compare management commentary, distributor trends, consumer indicators, commodity markets, and institutional analyst views. Identify the assumptions that would cause earnings growth and margins to strengthen or deteriorate. Generate a fully developed report with evidence-backed quantitative analysis, charts, tables, sensitivity analysis, and source citations.""",
    """Generate a comprehensive research report assessing whether India’s logistics and warehousing infrastructure can generate durable economic returns through 2030. Examine e-commerce penetration, manufacturing relocation, GST-driven consolidation, warehouse rents, land costs, occupancy, logistics yields, transport efficiency, automation capex, cold-chain demand, financing costs, tenant concentration, and competition among organized logistics operators and developers. Distinguish between structural demand growth and speculative warehouse supply. Evaluate the occupancy, rental, capex, and financing assumptions required for projects to achieve institutional return thresholds. Compare developers, logistics operators, e-commerce companies, infrastructure funds, lenders, and institutional analysts. Identify the conditions under which logistics infrastructure returns strengthen or deteriorate. Produce a full research report with quantitative analysis, relevant visuals, scenario testing, and evidence-linked citations.""",
]
EXPECTED_TOPICS = [
    "India’s private-bank credit cycle",
    "India’s FMCG industry",
    "India’s logistics and warehousing infrastructure",
]


def main() -> None:
    # Force the same fallback path seen when Groq keys are exhausted.
    intent_mod.get_groq_keys = lambda: []

    for prompt, expected in zip(PROMPTS, EXPECTED_TOPICS):
        intent = asyncio.run(intent_mod.resolve_request_intent(prompt))
        assert intent.source == "heuristic", intent
        assert intent.wants_report is True, intent
        assert intent.resolved_topic == expected, (intent.resolved_topic, expected)
        assert not intent.resolved_topic.startswith("Generate"), intent.resolved_topic
        assert not intent.resolved_topic.startswith("Generate a comprehensive"), intent.resolved_topic

    print("PASS: all 3 research prompts resolve to clean research subjects.")
    print("PASS: heuristic fallback no longer sends report boilerplate to search/entity resolution.")


if __name__ == "__main__":
    main()
